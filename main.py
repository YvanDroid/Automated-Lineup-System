def cut_ansi_string_into_parts(string_with_ansi_codes):
    """
    Converts a string with ambedded ANSI Color Codes and parses it to create
    a list of tuples describing pieces of the input string.
    :param string_with_ansi_codes:
    :return: [(sty, str, str, str), ...] A list of tuples. Each tuple has format: (text, text color, background color, effects)
    """
    color_codes_english = [
        "Black",
        "Red",
        "Green",
        "Yellow",
        "Blue",
        "Magenta",
        "Cyan",
        "White",
        "Reset",
    ]
    color_codes = ["30m", "31m", "32m", "33m", "34m", "35m", "36m", "37m", "0m"]
    effect_codes_english = [
        "Italic",
        "Underline",
        "Slow Blink",
        "Rapid Blink",
        "Crossed Out",
    ]
    effect_codes = ["3m", "4m", "5m", "6m", "9m"]
    background_codes = ["40m", "41m", "42m", "43m", "44m", "45m", "46m", "47m"]
    background_codes_english = [
        "Black",
        "Red",
        "Green",
        "Yellow",
        "Blue",
        "Magenta",
        "Cyan",
        "White",
    ]

    ansi_codes = color_codes + effect_codes

    tuple_list = []

    string_list = string_with_ansi_codes.split("\u001b[")

    if (len(string_list)) == 1:
        string_list = string_with_ansi_codes.split("\033[")

    for teststring in string_list:
        if teststring == string_with_ansi_codes:
            tuple_list += [(teststring, None, None, None)]
            break
        if any(code in teststring for code in ansi_codes):
            static_string = None
            color_used = None
            effect_used = None
            background_used = None
            for color in range(0, len(color_codes)):
                if teststring.startswith(color_codes[color]):
                    working_thread = teststring.split(color_codes[color])
                    ansi_strip = re.compile(r"\x1B[@-_][0-?]*[ -/]*[@-~]")
                    static_string = ansi_strip.sub("", working_thread[1])
                    color_used = color_codes_english[color]
            for effect in range(0, len(effect_codes)):
                if teststring.startswith(effect_codes[effect]):
                    working_thread = teststring.split(effect_codes[effect])
                    ansi_strip = re.compile(r"\x1B[@-_][0-?]*[ -/]*[@-~]")
                    static_string = ansi_strip.sub("", working_thread[1])
                    effect_used = effect_codes_english[effect]
            for background in range(0, len(background_codes)):
                if teststring.startswith(background_codes[background]):
                    working_thread = teststring.split(background_codes[background])
                    ansi_strip = re.compile(r"\x1B[@-_][0-?]*[ -/]*[@-~]")
                    static_string = ansi_strip.sub("", working_thread[1])
                    background_used = background_codes_english[background]
            try:
                if not tuple_list[len(tuple_list) - 1][0]:
                    if not tuple_list[len(tuple_list) - 1][1] == None:
                        color_used = tuple_list[len(tuple_list) - 1][1]
                    if not tuple_list[len(tuple_list) - 1][2] == None:
                        background_used = tuple_list[len(tuple_list) - 1][2]
                    if not tuple_list[len(tuple_list) - 1][3] == None:
                        effect_used = tuple_list[len(tuple_list) - 1][3]
                    tuple_list += [
                        (static_string, color_used, background_used, effect_used)
                    ]
                else:
                    tuple_list += [
                        (static_string, color_used, background_used, effect_used)
                    ]
            except Exception:
                tuple_list += [
                    (static_string, color_used, background_used, effect_used)
                ]

    new_tuple_list = []

    for x in range(0, len(tuple_list)):
        if tuple_list[x][0]:
            new_tuple_list += [
                [tuple_list[x][0], tuple_list[x][1], tuple_list[x][2], tuple_list[x][3]]
            ]

    return new_tuple_list


def multiline_update(window, key, asci_tuple_list):
    # inputs a list and a subsequent key and updates the multiline
    # list is the tuple list from the ansi string tuple generated by the above function
    for item in asci_tuple_list:
        if item[1] == "Reset":
            item[1] = None
        window[key].update(
            item[0] + ", ",
            text_color_for_value=item[1],
            background_color_for_value=item[2],
            append=True,
            autoscroll=True,
        )
    window.refresh()


def GetFile():
    filename = sg.popup_get_file(
        "Select a lineup csv", no_window=True, file_types=(("CSV Files", "*.csv"),)
    )
    return None if filename == "" else filename


def CreateTable(dataframe, rc_menu):
    data = dataframe.values.tolist()
    headers = dataframe.columns.tolist()

    table = [
        [
            sg.Table(
                values=data,
                headings=headers,
                display_row_numbers=True,
                auto_size_columns=False,
                num_rows=min(25, len(data)),
                enable_events=True,
                enable_click_events=True,
                key="-TABLE-",
                right_click_menu=rc_menu,
                right_click_selects=True,
            )
        ]
    ]

    return table, headers


def TableReader(filename, rc_menu):
    try:
        df = pd.read_csv(filename, sep=",", engine="python")

    except:
        sg.popup_error("Error Reading File")

    table, headers = CreateTable(df, rc_menu)
    return table, df, headers


def TableUpdate(dataframe, window, window_function, **args):
    # Recreate the window for the table
    # recreate a window by passing the window function
    # Close the old window

    window.close()
    window_function(dataframe, **args)


def create_edit_menu(dataframe, mode=0):  # Editing = 1, Creating = 0
    ce_rc_menu = [
        "&Right",
        ["Delete Column", "Select Column to Replace", "Save to File"],
    ]
    ce_title = "Table Editor"
    if mode == 1:  # No name given
        ce_filename = GetFile()
        if ce_filename == (): # When cancelling out of dialogue menu, it returns an empty tuple.
            sg.popup("No file selected. Returning to menu")
            return
        ce_table, ce_dF, ce_headers = TableReader(ce_filename, ce_rc_menu)
    if mode == 0:
        ce_dF = dataframe
        ce_table, ce_headers = CreateTable(ce_dF, ce_rc_menu)

    ce_form = [
        [sg.Text("Header")],
        [sg.Input("", key="-CEHEAD-"), sg.Button("Clear", key="-CEHEADCLR-")],
        [sg.Text("List")],
        [sg.Input("", key="-CELIST-"), sg.Button("Clear", key="-CELISTCLR-")],
        [sg.Button("Submit Column"), sg.Button("Replace Selected Column")],
    ]

    ce_menu = [
        [sg.Column(ce_table, key="-CE1-"), sg.Column(ce_form, key="-CEFORM-")],
        [sg.Button("Main Menu"), sg.Button("Save to File"), sg.Button("Open New File")],
    ]  # Layout
    ce_window = sg.Window(ce_title, ce_menu)

    ce_table = ce_window["-TABLE-"].Widget
    selected_column = 0

    while True:
        event3, values3 = ce_window.read()
        print(f"event3's output: {event3}")
        print(f"values3's output: {values3}")
        if event3 == "Main Menu" or event3 == sg.WIN_CLOSED:
            break
        if "+CLICKED+" in event3:
            selected_column = event3[2][1]
            # The second value in the tuple given by the table
            print(selected_column)

        if event3 == "Submit Column":

            ce_dF = tr.AddColumn(
                ce_dF, header=values3["-CEHEAD-"], content=values3["-CELIST-"]
            )
            TableUpdate(ce_dF, ce_window, create_edit_menu, mode=0)

        if event3 == "Delete Column" or event3 == "Delete Selected Column":
            print(ce_headers[selected_column])
            ce_dF = tr.RemoveColumn(ce_dF, str(ce_headers[selected_column]))
            TableUpdate(ce_dF, ce_window, create_edit_menu, mode=0)

        if event3 == "Save to File":
            tr.CreateFile(
                ce_dF,
                file_name=sg.popup_get_text(
                    "Please enter the name to save",
                    title="Save file name",
                    default_text="Lineup-",
                ),
            )
        if event3 == "Select Column to Replace":
            values = ce_dF[ce_headers[selected_column]].tolist()
            print(values)
            value_list_str = ""
            for index, element in enumerate(values):
                if index == len(values) - 1:
                    value_list_str += str(element)
                else:
                    value_list_str += str(element) + ","
            ce_window["-CELIST-"].update(value_list_str)
            ce_window["-CEHEAD-"].update(ce_headers[selected_column])
            # Grab the selected column's data and place it into the headers
            # Probably grab the last header selected to replace too

        if event3 == "Replace Selected Column":
            # Get data from text box and place into the header specified
            # Refresh window#
            print(
                f"Replacing: {ce_headers[selected_column]} with {values3['-CEHEAD-']}"
            )
            tr.ReplaceColumn(
                ce_dF,
                str(ce_headers[selected_column]),
                values3["-CELIST-"],
                values3["-CEHEAD-"],
            )
            TableUpdate(ce_dF, ce_window, create_edit_menu, mode=0)

    ce_window.close()


